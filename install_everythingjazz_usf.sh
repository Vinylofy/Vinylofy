#!/usr/bin/env bash
set -Eeuo pipefail

fail() {
  printf '\n[ERROR] %s\n' "$*" >&2
  exit 1
}

command -v git >/dev/null 2>&1 || fail "git ontbreekt"
command -v python >/dev/null 2>&1 || fail "python ontbreekt"
command -v base64 >/dev/null 2>&1 || fail "base64 ontbreekt"
command -v tar >/dev/null 2>&1 || fail "tar ontbreekt"

ROOT="$(git rev-parse --show-toplevel 2>/dev/null)" || fail "voer dit script binnen een git-repository uit"
cd "$ROOT"

REMOTE="$(git remote get-url origin 2>/dev/null || true)"
case "$REMOTE" in
  https://github.com/Vinylofy/Vinylofy|https://github.com/Vinylofy/Vinylofy.git|git@github.com:Vinylofy/Vinylofy.git)
    ;;
  *) fail "onverwachte origin: ${REMOTE:-<geen>}; verwacht Vinylofy/Vinylofy" ;;
esac

printf '== Repository ==\n'
printf 'root:   %s\n' "$ROOT"
printf 'origin: %s\n' "$REMOTE"
printf 'branch: %s\n' "$(git branch --show-current)"
printf '\n== Bestaande gitstatus ==\n'
git status --short

TARGETS=(
  scripts/scrapers/usf/jobs/refresh_everythingjazz_listing_prices.py
  scripts/scrapers/usf/jobs/detail_everythingjazz.py
  scripts/scrapers/usf/jobs/stage_everythingjazz.py
  scripts/scrapers/usf/jobs/promote_everythingjazz.py
  scripts/scrapers/usf/jobs/quarantine_everythingjazz.py
  scripts/scrapers/usf/jobs/run_everythingjazz_pipeline.py
  scripts/sql/check_everythingjazz.sql
  .github/workflows/usf-everythingjazz-listing.yml
  .github/workflows/usf-everythingjazz-detail.yml
)

for target in "${TARGETS[@]}"; do
  [[ ! -e "$target" ]] || fail "doelbestand bestaat al; niets overschreven: $target"
done

SHIPPING_CSV="data/shipping/vinylofy_shipping_rules_nl.csv"
[[ -f "$SHIPPING_CSV" ]] || fail "shippingbestand ontbreekt: $SHIPPING_CSV"
[[ -f scripts/tools/import_shipping_rules.py ]] || fail "bestaande shippingimporter ontbreekt"
[[ -f scripts/scrapers/usf/core/listing_price_sync.py ]] || fail "USF listing core ontbreekt"
[[ -f scripts/scrapers/usf/core/staging.py ]] || fail "USF staging core ontbreekt"
[[ -f scripts/scrapers/usf/core/promotion.py ]] || fail "USF promotion core ontbreekt"
[[ -f scripts/scrapers/usf/core/promotion_writer.py ]] || fail "USF promotion writer ontbreekt"

python - "$SHIPPING_CSV" <<'PY'
from __future__ import annotations
import csv
import sys
from pathlib import Path

path = Path(sys.argv[1])
required = {
    "shop_slug", "shop_name", "country_code", "currency",
    "shipping_cost_cents", "free_shipping_threshold_cents",
    "shipping_logic", "shipping_note", "confidence", "source_url",
    "source_url_2", "verified_at", "active",
}
with path.open(newline="", encoding="utf-8-sig") as handle:
    reader = csv.DictReader(handle)
    fields = set(reader.fieldnames or [])
    missing = sorted(required - fields)
    if missing:
        raise SystemExit(f"[ERROR] shippingkolommen ontbreken: {missing}")
    rows = [row for row in reader if row.get("shop_slug") == "everythingjazz"]

if len(rows) > 1:
    raise SystemExit("[ERROR] meerdere bestaande everythingjazz-shippingregels aangetroffen")
if rows:
    row = rows[0]
    expected = {
        "country_code": "NL",
        "currency": "EUR",
        "shipping_cost_cents": "995",
        "free_shipping_threshold_cents": "",
        "shipping_logic": "flat",
        "active": "true",
    }
    mismatches = {
        key: (row.get(key), value)
        for key, value in expected.items()
        if (row.get(key) or "").strip().lower() != value.lower()
    }
    if mismatches:
        raise SystemExit(
            "[ERROR] bestaande everythingjazz-shippingregel wijkt af: "
            + repr(mismatches)
        )
    print("[CHECK] bestaande shippingregel is al exact; installer laat hem staan")
else:
    print("[CHECK] shippingregel ontbreekt en kan veilig worden toegevoegd")
PY

TMP_DIR="$(mktemp -d)"
BACKUP_DIR="/tmp/vinylofy-everythingjazz-backup-$(date +%Y%m%d-%H%M%S)"
cleanup() { rm -rf "$TMP_DIR"; }
trap cleanup EXIT
mkdir -p "$BACKUP_DIR"
cp -a "$SHIPPING_CSV" "$BACKUP_DIR/"

